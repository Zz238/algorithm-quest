const quiz = (question, options, answer, explanation) => {
  const rotate = [...question].reduce((sum, char) => sum + char.charCodeAt(0), 0) % options.length;
  return {
    kind: 'choice',
    question,
    options: [...options.slice(rotate), ...options.slice(0, rotate)],
    answer: (answer - rotate + options.length) % options.length,
    explanation,
    hints: ['先把题中的具体过程走一遍，再选择。'],
  };
};
